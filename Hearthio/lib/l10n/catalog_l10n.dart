import 'app_localizations.dart';

extension HearthioCatalogLocalizations on AppLocalizations {
  String spaceTypeLabel(String type) => switch (type) {
    '客厅' => spaceTypeLivingRoom,
    '卧室' => spaceTypeBedroom,
    '厨房' => spaceTypeKitchen,
    '卫生间' => spaceTypeBathroom,
